"""B04: writes C++ row structs for every table in design/tech/datatable_map.csv, plus the manifest sf_import_data.py reads.

Types are inferred from the CSV values; row_struct_overrides.json ({"folder/table.csv": {"header": "cpp type"}}) wins.
"""
import csv
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLAN = ROOT.parent
DATA = PLAN / "data"
OVERRIDES = json.loads(Path(__file__).with_name("row_struct_overrides.json").read_text())
ID = re.compile(r"[A-Z][A-Z0-9]*(_[A-Z0-9]+)+")
INT = re.compile(r"-?\d+")
FLOAT = re.compile(r"-?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?")
BOOLS = {"true", "false", "yes", "no", "y", "n"}  # sf_import_data.py writes these as true/false


def infer(values):
    values = [v for v in values if v != ""]
    if not values:
        return "FString"
    if all(v.lower() in BOOLS for v in values):
        return "bool"
    if all(INT.fullmatch(v) for v in values):
        return "int32" if all(-2**31 <= int(v) < 2**31 for v in values) else "int64"
    if all(FLOAT.fullmatch(v) for v in values):
        return "float"
    return "FName" if all(ID.fullmatch(v) for v in values) else "FString"


def prop_name(header, used):
    name = "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", header)) or "Col"
    if name[0].isdigit():
        name = "N" + name
    base, i = name, 2
    while name in used:
        name, i = f"{base}{i}", i + 1
    used.add(name)
    return name


def default(cpp):
    return {"bool": " = false", "int32": " = 0", "int64": " = 0", "float": " = 0.f"}.get(cpp, "")


tables = [r for r in csv.DictReader(open(PLAN / "design/tech/datatable_map.csv"))
          if r["ue_type"].split()[0] in ("DataTable", "DataTable+Code", "CurveTable", "StringTable")]
struct_count = Counter(r["ue_struct"] for r in tables if r["ue_struct"] != "-")
manifest, structs = [], []
for t in tables:
    path = DATA / t["csv"]
    if not path.exists():
        print("skipped, CSV missing:", t["csv"])
        continue
    rows = list(csv.reader(open(path, newline="", encoding="utf-8")))
    header, body = rows[0], rows[1:]
    kind = t["ue_type"].split()[0].replace("+Code", "")
    entry = {"csv": t["csv"], "type": kind, "asset": t["ue_asset"], "grouped": "grouped" in t["ue_type"]}
    if kind == "DataTable":
        struct = t["ue_struct"]
        if struct_count[struct] > 1:
            struct = "F" + t["csv"].split("/")[0].title() + struct[1:]
        overrides, used, columns = OVERRIDES.get(t["csv"], {}), set(), []
        for i, h in enumerate(header):
            if i == 0 and not entry["grouped"]:
                continue  # becomes the RowName
            cpp = overrides.get(h) or infer([r[i] for r in body if i < len(r)])
            columns.append([h, prop_name(h, used), cpp])
        entry.update(struct=struct, columns=columns)
        props = "".join(f"\n\t// {h}\n\tUPROPERTY(EditAnywhere, BlueprintReadOnly)\n\t{cpp} {p}{default(cpp)};\n"
                         for h, p, cpp in columns)
        structs.append(f"// {t['csv']}\nUSTRUCT(BlueprintType)\nstruct SFDATA_API {struct} : public FTableRowBase\n{{"
                       f"\n\tGENERATED_BODY()\n{props}}};\n")
    manifest.append(entry)

out = ROOT / "Source/SfData/Public/SfDataRows.h"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("// Generated by tools/GenRowStructs.py from game-plan/data. Do not edit.\n#pragma once\n\n"
               '#include "Engine/DataTable.h"\n#include "SfDataRows.generated.h"\n\n' + "\n".join(structs), newline="\n")
(ROOT / "Content/Python/sf_import_manifest.json").write_text(json.dumps(manifest, indent=1) + "\n", newline="\n")
print(f"{len(structs)} row structs, {len(manifest)} tables in manifest")
