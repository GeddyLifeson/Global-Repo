"""B29: turns the event tables in design/tech/06-telemetry-crash-liveops.md into the SfTelemetry schema.

Writes Source/SfTelemetry/Public/SfTelemetryEvents.h (event name constants) and
Source/SfTelemetry/Private/SfTelemetrySchema.inl (fields, retail sample rate, playtest-only flag).
Bump SCHEMA_VERSION whenever an event or field changes.
"""
import re
from pathlib import Path

SCHEMA_VERSION = 1
ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT.parent / "design/tech/06-telemetry-crash-liveops.md"
OUT_H = ROOT / "Source/SfTelemetry/Public/SfTelemetryEvents.h"
OUT_INL = ROOT / "Source/SfTelemetry/Private/SfTelemetrySchema.inl"

# Doc phrases that do not reduce to a field name by rule.
FIELD_NAMES = {
    "cause (ATK_/MOV_ ID)": "cause_id", "play time": "play_time_s", "duration": "duration_s",
    "time since last": "time_since_last_s", "source or sink": "flow", "1% low": "low_1pct_fps",
    "price and currency": ["price", "currency"], "enter and exit": "state", "Echo or co-op": "summon_kind",
    "boss or area ID": "target_id", "strike or raid ID": "activity_id", "mounted flag": "mounted",
    "tracked flag": "tracked", "seconds": "duration_s", "time spent": "time_spent_s",
    "time since area entry": "time_since_area_entry_s", "rating band": "rating_band",
    "success or failure code": "result", "researcher note tag": "note_tag", "latency": "latency_ms",
    "memory": "memory_mb", "tester ID in playtest builds": "tester_id",
}


def field_names(cell):
    out = []
    for raw in re.split(r",(?![^(]*\))", cell):
        raw = raw.strip()
        name = FIELD_NAMES.get(raw)
        if name is None:
            base = re.sub(r"\s*\(.*\)", "", raw)
            name = FIELD_NAMES.get(base) or re.sub(r"[^a-z0-9]+", "_", base.lower().replace("_ id", "_id")).strip("_")
        out += name if isinstance(name, list) else [name]
    return out


def table_rows(text):
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and cells[0] not in ("Event", "ID") and not set(cells[0]) <= set("- "):
            yield cells


def parse():
    events = {}
    for cells in table_rows(DOC.read_text(encoding="utf-8")):
        if cells[0].startswith("TR_"):
            cells = cells[1:]
        title, fields = cells[0], field_names(cells[1])
        note = (re.search(r"\((.*)\)", title) or [None, ""])[1]
        rate = re.search(r"(\d+)%", note)
        retail = int(rate[1]) / 100 if rate else 1.0
        playtest = 1.0 if "playtest" in note else retail
        if "playtest builds only" in note:
            retail = 0.0
        if title.endswith("result field"):
            base = events[title.split()[0]]["fields"]
            base += [f for f in fields if f not in base]
            continue
        for name in re.sub(r"\s*\(.*\)", "", title).split(" / "):
            events[name.strip()] = {"fields": fields, "retail": retail, "playtest": playtest}
    return events


def pascal(name):
    return "".join(p.capitalize() for p in name.split("_"))


def main():
    events = parse()
    h = ["// Generated by tools/gen_telemetry_schema.py from design/tech/06-telemetry-crash-liveops.md. Do not edit.",
         "#pragma once", "", "#include \"CoreMinimal.h\"", "",
         f"#define SF_TELEMETRY_SCHEMA_VERSION {SCHEMA_VERSION}", "", "namespace SfTelemetryEvent", "{"]
    h += [f"\tinline constexpr TCHAR {pascal(n)}[] = TEXT(\"{n}\");" for n in events]
    h += ["}", ""]
    inl = ["// Generated by tools/gen_telemetry_schema.py from design/tech/06-telemetry-crash-liveops.md. Do not edit.",
           "// Name, comma-separated fields, retail sample rate (0 = playtest builds only), playtest sample rate."]
    for n, e in events.items():
        inl.append(f"{{ TEXT(\"{n}\"), TEXT(\"{','.join(e['fields'])}\"), {e['retail']}f, {e['playtest']}f }},")
    OUT_H.write_text("\n".join(h), encoding="utf-8")
    OUT_INL.write_text("\n".join(inl) + "\n", encoding="utf-8")
    print(f"{len(events)} events, schema v{SCHEMA_VERSION}")


if __name__ == "__main__":
    main()
