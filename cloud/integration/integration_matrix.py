# S6919 integration_matrix.py: builds plans/INTEGRATION_MATRIX.md and INTEGRATION_TICKETS.tsv (every system x every system) from the port data in matrix_data.py
# Usage: python3 -I integration_matrix.py OUT_DIR   (writes INTEGRATION_MATRIX.md, INTEGRATION_MATRIX.csv, INTEGRATION_TICKETS.tsv)
import sys, os, csv, itertools
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from matrix_data import BRIDGES, SYSTEMS, OVERRIDES, LANES, HUBS, NOUNS, HUB_TEXT

WEAK = set("KGV")  # universal facets every system has; a pair needing only these still gets a row but is flagged
PRIO = {b: i for i, b in enumerate("EFLMCSWUHPAKGV")}


def key(a, b):
    return tuple(sorted((a, b)))


def hub_lines(a, b):
    out = []
    for h, o in ((a, b), (b, a)):
        if h in HUBS and o not in HUBS:
            t, u, op, j = NOUNS[o]
            out.append(HUB_TEXT[h].format(thing_o=t, unit_o=u[0].upper() + u[1:], output_o=op, job_o=j, thing_h=NOUNS[h][0]))
    if a in HUBS and b in HUBS:
        for h, o in ((a, b), (b, a)):
            t, u, op, j = NOUNS[o]
            out.append(HUB_TEXT[h].format(thing_o=t, unit_o=u[0].upper() + u[1:], output_o=op, job_o=j, thing_h=NOUNS[h][0]))
    return out


def cells():
    ids = list(SYSTEMS)
    out = {}
    for a, b in itertools.combinations(ids, 2):
        found = []
        for x, y in ((a, b), (b, a)):
            for f, ph in SYSTEMS[x]["gives"].items():
                if f in SYSTEMS[y]["takes"]:
                    found.append((f, x, y, ph, SYSTEMS[y]["takes"][f]))
        found.sort(key=lambda t: PRIO[t[0]])
        strong = [t for t in found if t[0] not in WEAK]
        out[key(a, b)] = {"hub": hub_lines(a, b), "strong": strong, "weak": [t for t in found if t[0] in WEAK], "over": OVERRIDES.get(key(a, b))}
    return out


def render(c):
    ids = list(SYSTEMS)
    L = ["# INTEGRATION MATRIX: every system with every other system (D1141, generated by S6919)", "",
         "Rule (Marlon 11-03): everything integrates with everything. Train fuelled by mana is the model case. This file lists, for every pair of systems in the pack, at least one real interaction, built on a few universal bridges so nothing is a one-off.",
         "Source of truth: `cloud/integration/matrix_data.py` in Global-Repo (what each system gives and takes). Re-run S6919 after editing it. Sits beside plans/INTEGRATION.md (module definition of done) and plans/UNITS.md (units).", "",
         "## 1. The universal bridges (build these once, every system plugs in)", "",
         "| Id | Bridge | Currency / unit | Lives in | Rule |", "|---|---|---|---|---|"]
    for k, v in BRIDGES.items():
        L.append(f"| {k} | {v[0]} | {v[1]} | {v[2]} | {v[3]} |")
    L += ["", f"## 2. Systems ({len(ids)})", "", "| Code | System | Lane that owns pair work |", "|---|---|---|"]
    for i, s in SYSTEMS.items():
        L.append(f"| {i} | {s['name']} | {LANES[s['lane']][0]} |")
    n_over = sum(1 for e in c.values() if e["over"])
    L += ["", f"Method: {n_over} of {len(c)} pairs have a hand-written interaction; the rest take the hub template (animation, progression, Codex, upgrades, economy, NPC jobs, storage, circuits, autonomy, weather, culture) filled with the other system's own nouns, plus the bridge channels in section 4. All are designs on paper; section 5 says what is built.", "",
          "## 3. Grid: bridge letters per pair (blank diagonal; * = concrete override)", "",
          "| |" + "|".join(ids) + "|", "|---|" + "|".join("---" for _ in ids) + "|"]
    for a in ids:
        row = []
        for b in ids:
            if a == b:
                row.append("")
                continue
            e = c[key(a, b)]
            letters = "".join(dict.fromkeys(t[0] for t in e["strong"]))[:4] or "·"
            row.append(letters + ("*" if e["over"] else ""))
        L.append(f"| **{a}** |" + "|".join(row) + "|")
    L += ["", "## 4. Pairs", "", "Each pair: a concrete interaction (`*`) is a concrete design. A pair marked CHANNEL has the bridge both systems already plug into, listed as `[bridge] giver > taker: what it gives; what it takes`; it is a ticket for the owning lanes to turn into a concrete recipe, block or NPC job, not a finished design. Age rule: an interaction unlocks at the later of the two systems' Ages and is gated by the same recipe or station as the thing it uses.", ""]
    for a in ids:
        L.append(f"### {a} {SYSTEMS[a]['name']}")
        for b in ids[ids.index(a) + 1:]:
            e = c[key(a, b)]
            parts = []
            if e["over"]:
                parts.append("* " + e["over"])
            for h in e["hub"]:
                parts.append("hub: " + h)
            for f, x, y, g, t in e["strong"][:2]:
                parts.append(f"[{f}] {x}>{y}: {g}; {t}")
            if not e["over"] and not e["hub"]:
                parts.insert(0, "CHANNEL (owning lanes write the concrete case):")
            if not parts:
                for f, x, y, g, t in e["weak"][:2]:
                    parts.append(f"[{f}] {x}>{y}: {g}; {t}")
            L.append(f"- **{b}**: " + " | ".join(parts))
        L.append("")
    L += ["## 5. Build status", "", "Built: carrier table (`diaithir-units` Fuels/Engine) for fuels; Tobardealain and Lochrandraoidheachd (magic to FE and back), EU and air converters, molten tank (`diaithir-bridges`). See PR list in plans/INTEGRATION.md when merged. Everything else here is a design that the owning lane builds; INTEGRATION_TICKETS.tsv lists each lane's pairs.", ""]
    return "\n".join(L)


def main(out):
    c = cells()
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "INTEGRATION_MATRIX.md"), "w") as f:
        f.write(render(c))
    with open(os.path.join(out, "INTEGRATION_MATRIX.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["a", "b", "bridges", "written", "strong_hits", "owner_lane_a", "owner_lane_b"])
        for (a, b), e in c.items():
            w.writerow([a, b, "".join(dict.fromkeys(t[0] for t in e["strong"])), 1 if (e["over"] or e["hub"]) else 0, len(e["strong"]),
                        SYSTEMS[a]["lane"], SYSTEMS[b]["lane"]])
    with open(os.path.join(out, "INTEGRATION_TICKETS.tsv"), "w") as f:
        f.write("lane\tlane_thread\tconcrete_pairs\tchannel_only_pairs\n")
        by = {}
        for (a, b), e in c.items():
            for ln in {SYSTEMS[a]["lane"], SYSTEMS[b]["lane"]}:
                by.setdefault(ln, [[], []])[0 if (e["over"] or e["hub"]) else 1].append(f"{a}x{b}")
        for ln, ps in sorted(by.items()):
            f.write(f"{LANES[ln][0]}\t{LANES[ln][1]}\t{' '.join(ps[0])}\t{' '.join(ps[1])}\n")
    thin = [(a, b) for (a, b), e in c.items() if not e["strong"] and not e["over"] and not e["hub"]]
    n = len(c)
    w = sum(1 for e in c.values() if e["over"] or e["hub"])
    print(f"{len(SYSTEMS)} systems, {n} pairs, {w} concrete, {n - w} channel-only, {len(thin)} with no bridge at all: {thin}")


if __name__ == "__main__":
    main(sys.argv[1])
